-- Validation queries for the test runs (TC-02...TC-08). Run with role ADF_SAP_LOADER or an analyst role.
USE WAREHOUSE ADF_SAP_WH;
USE DATABASE SAP_DB;

-- V-01 rows per table and the last load (compare with SE16N row counts in SAP)
SELECT 'KNA1' AS TABLE_NAME, COUNT(*) AS ROWS_CORE, MAX(_LOADED_AT) AS LAST_LOAD FROM SAP_CORE.KNA1
UNION ALL SELECT 'MARA', COUNT(*), MAX(_LOADED_AT) FROM SAP_CORE.MARA
UNION ALL SELECT 'VBAK', COUNT(*), MAX(_LOADED_AT) FROM SAP_CORE.VBAK;

-- V-02 no duplicate keys in the core tables (must return 0 rows)
SELECT KUNNR, COUNT(*) FROM SAP_CORE.KNA1 GROUP BY KUNNR HAVING COUNT(*) > 1;
SELECT MATNR, COUNT(*) FROM SAP_CORE.MARA GROUP BY MATNR HAVING COUNT(*) > 1;
SELECT VBELN, COUNT(*) FROM SAP_CORE.VBAK GROUP BY VBELN HAVING COUNT(*) > 1;

-- V-03 SAP dates converted (no landing value other than '00000000' or empty may become NULL)
SELECT L.KUNNR, L.ERDAT FROM SAP_LANDING.KNA1 L JOIN SAP_CORE.KNA1 C ON C.KUNNR = L.KUNNR
WHERE C.ERDAT IS NULL AND NULLIF(NULLIF(L.ERDAT, '00000000'), '') IS NOT NULL;

-- V-04 the VBAK filter was applied in SAP (must return 0 rows)
SELECT VBELN, ERDAT FROM SAP_CORE.VBAK WHERE ERDAT < '2026-01-01';

-- V-05 one ADF run per load: rows touched by the latest run
SELECT _ADF_RUN_ID, COUNT(*) FROM SAP_CORE.KNA1 GROUP BY _ADF_RUN_ID ORDER BY MAX(_LOADED_AT) DESC LIMIT 3;

-- V-06 Snowflake side of the load (COPY history of the landing tables in the last day)
SELECT TABLE_NAME, STATUS, ROW_COUNT, ROW_PARSED, FIRST_ERROR_MESSAGE, LAST_LOAD_TIME
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'SAP_LANDING.KNA1', START_TIME => DATEADD(DAY, -1, CURRENT_TIMESTAMP())));

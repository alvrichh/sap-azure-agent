#!/usr/bin/env python3
"""Generates the pipeline control file and the Snowflake DDL from adf/objects.json.

  python3 examples/adf-sap-to-snowflake/tools/generate.py           # write files
  python3 examples/adf-sap-to-snowflake/tools/generate.py --check   # fail if the files are out of date

Every identifier is validated (uppercase SAP/Snowflake names only) before it is placed in SQL, so the
statements that Data Factory runs through dynamic content can't be altered by the control file.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "adf/objects.json"
CONTROL = ROOT / "adf/sap-snowflake-objects.json"
DDL = ROOT / "snowflake/02-tables.sql"

IDENT = re.compile(r"^[A-Z][A-Z0-9_]{0,29}$")
TYPE = re.compile(r"^(VARCHAR\(\d{1,4}\)|NUMBER\(\d{1,2},\d{1,2}\)|DATE)$")
# SAP OPEN SQL filter for RFC_READ_TABLE: FIELD OP 'literal' [AND ...], operators of the SAP Table connector
FILTER = re.compile(r"^$|^[A-Z][A-Z0-9_]* (EQ|NE|LT|LE|GT|GE) '[A-Z0-9 ]{0,20}'( AND [A-Z][A-Z0-9_]* (EQ|NE|LT|LE|GT|GE) '[A-Z0-9 ]{0,20}')*$")
META = [("_LOADED_AT", "TIMESTAMP_NTZ"), ("_ADF_RUN_ID", "VARCHAR(36)")]


def validate(spec):
    problems = []
    for schema in (spec["landingSchema"], spec["targetSchema"]):
        if not IDENT.match(schema):
            problems.append(f"bad schema name {schema!r}")
    seen = set()
    for obj in spec["objects"]:
        t = obj["sapTable"]
        if not IDENT.match(t) or t in seen:
            problems.append(f"bad or duplicate table {t!r}")
        seen.add(t)
        names = [c["name"] for c in obj["columns"]]
        for c in obj["columns"]:
            if not IDENT.match(c["name"]) or not TYPE.match(c["type"]):
                problems.append(f"{t}.{c['name']}: bad name or type {c['type']!r}")
            if c["type"] == "DATE" and c.get("sapType") != "DATS":
                problems.append(f"{t}.{c['name']}: DATE columns must come from SAP DATS")
        if len(set(names)) != len(names):
            problems.append(f"{t}: duplicate columns")
        if not obj["keyColumns"] or not set(obj["keyColumns"]) <= set(names):
            problems.append(f"{t}: key columns must be a non-empty subset of the columns")
        if not FILTER.match(obj.get("sapFilter", "")):
            problems.append(f"{t}: filter {obj.get('sapFilter')!r} not in the allowed form")
    if problems:
        raise ValueError("; ".join(problems))


def landing_type(col):
    return "VARCHAR(8)" if col["type"] == "DATE" else col["type"]


def source_expr(col):
    """Expression that converts a landing column to the target type."""
    if col["type"] == "DATE":  # SAP DATS 'YYYYMMDD'; '00000000' (initial) becomes NULL
        return f"TRY_TO_DATE(NULLIF(S.{col['name']}, '00000000'), 'YYYYMMDD')"
    return f"S.{col['name']}"


def merge_sql(spec, obj):
    land, tgt = f"{spec['landingSchema']}.{obj['sapTable']}", f"{spec['targetSchema']}.{obj['sapTable']}"
    keys = obj["keyColumns"]
    cols = [c["name"] for c in obj["columns"]]
    non_keys = [c for c in obj["columns"] if c["name"] not in keys]
    by_name = {c["name"]: c for c in obj["columns"]}
    # Deduplicate the landing rows per key so MERGE is deterministic (Snowflake rejects nondeterministic updates by default)
    src = (f"SELECT * FROM {land} QUALIFY ROW_NUMBER() OVER (PARTITION BY {', '.join(keys)} ORDER BY {', '.join(keys)}) = 1")
    on = " AND ".join(f"T.{k} = S.{k}" for k in keys)
    upd = ", ".join([f"T.{c['name']} = {source_expr(c)}" for c in non_keys] + ["T._LOADED_AT = CURRENT_TIMESTAMP()", "T._ADF_RUN_ID = '{runId}'"])
    ins_cols = ", ".join(cols + [m[0] for m in META])
    ins_vals = ", ".join([source_expr(by_name[c]) for c in cols] + ["CURRENT_TIMESTAMP()", "'{runId}'"])
    return (f"MERGE INTO {tgt} T USING ({src}) S ON {on} "
            f"WHEN MATCHED THEN UPDATE SET {upd} "
            f"WHEN NOT MATCHED THEN INSERT ({ins_cols}) VALUES ({ins_vals})")


def build(spec):
    validate(spec)
    control, ddl = [], [
        "-- Generated by tools/generate.py from adf/objects.json. Do not edit by hand.",
        f"-- Run after 01-setup.sql, with the role that owns {spec['landingSchema']} and {spec['targetSchema']}.",
        "",
    ]
    for obj in spec["objects"]:
        t = obj["sapTable"]
        control.append({
            "sapTable": t,
            "sapFields": ", ".join(c["name"] for c in obj["columns"]),
            "sapFilter": obj.get("sapFilter", ""),
            "landingSchema": spec["landingSchema"],
            "landingTable": t,
            "targetTable": f"{spec['targetSchema']}.{t}",
            "keyColumns": obj["keyColumns"],
            "countSql": f"SELECT COUNT(*) AS ROW_COUNT FROM {spec['landingSchema']}.{t}",
            "mergeSql": merge_sql(spec, obj),
        })
        ddl.append(f"-- {t}: {obj['description']}")
        ddl.append(f"CREATE TABLE IF NOT EXISTS {spec['landingSchema']}.{t} (\n" +
                   ",\n".join(f"  {c['name']} {landing_type(c)}" for c in obj["columns"]) + "\n);")
        ddl.append(f"CREATE TABLE IF NOT EXISTS {spec['targetSchema']}.{t} (\n" +
                   ",\n".join(f"  {c['name']} {c['type']}" for c in obj["columns"]) + ",\n" +
                   ",\n".join(f"  {n} {ty}" for n, ty in META) + ",\n" +
                   f"  CONSTRAINT PK_{t} PRIMARY KEY ({', '.join(obj['keyColumns'])})\n);")
        ddl.append("")
    return json.dumps(control, indent=2) + "\n", "\n".join(ddl)


def main():
    control, ddl = build(json.loads(SOURCE.read_text()))
    if "--check" in sys.argv:
        stale = [p.name for p, text in ((CONTROL, control), (DDL, ddl)) if not p.exists() or p.read_text() != text]
        print("up to date" if not stale else f"out of date: {stale} (run tools/generate.py)")
        sys.exit(1 if stale else 0)
    CONTROL.write_text(control)
    DDL.write_text(ddl)
    print(f"wrote {CONTROL.relative_to(ROOT)} and {DDL.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
